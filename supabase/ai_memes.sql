-- Wry: user-prompted AI memes.
-- A signed-in user gives a topic; the server asks an OpenAI model to write the caption
-- and pick an image from the stock library below, then saves the result as a caption row.
-- Paste into Supabase Dashboard -> SQL Editor -> New query -> Run. Safe to re-run.
--
-- Additive only: no rows are changed or deleted. Existing captions become source = 'human'.
-- Writes to stock_images and AI captions happen server-side with the service-role key;
-- there are still no INSERT/UPDATE/DELETE policies for anon or authenticated.

-- ---------------------------------------------------------------------------
-- 1. Stock image library (images live in the public "stock" Storage bucket).
-- ---------------------------------------------------------------------------
create table if not exists public.stock_images (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  image_url text not null check (image_url ~ '^(/[^/]|https://)'),
  alt text not null,
  description text not null, -- what the model reads when picking an image
  tags text[] not null default '{}',
  credit text,
  source_url text check (source_url is null or source_url ~ '^https://'),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.stock_images enable row level security;

drop policy if exists "Anyone can read stock images" on public.stock_images;
create policy "Anyone can read stock images"
  on public.stock_images for select
  to anon, authenticated
  using (true);

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('stock', 'stock', true, 2097152, array['image/jpeg', 'image/webp'])
on conflict (id) do update
  set public = excluded.public,
      file_size_limit = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;

-- ---------------------------------------------------------------------------
-- 2. Mark where each caption came from.
-- ---------------------------------------------------------------------------
alter table public.captions
  add column if not exists source text not null default 'human',
  add column if not exists ai_model text,
  add column if not exists prompt text, -- the user's topic, moderated before saving
  add column if not exists created_by uuid references auth.users (id) on delete set null,
  add column if not exists stock_image_id bigint references public.stock_images (id) on delete set null;

alter table public.captions drop constraint if exists captions_source_check;
alter table public.captions
  add constraint captions_source_check check (source in ('human', 'ai'));

create index if not exists captions_created_by_created_at_idx
  on public.captions (created_by, created_at);

-- ---------------------------------------------------------------------------
-- 3. Keep created_by private. The "Anyone can read captions" policy still applies to rows,
--    but anon/authenticated may only read these columns. The app reads a user's own memes
--    server-side with the service role. NOTE: new caption columns must be added here to be
--    readable through the public API.
-- ---------------------------------------------------------------------------
revoke select on public.captions from anon, authenticated;
grant select (
  id, text, created_at, image_url, image_alt, image_credit, image_source_url,
  source, ai_model, prompt, stock_image_id
) on public.captions to anon, authenticated;
